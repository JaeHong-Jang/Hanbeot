// events/*.schema.json -> apps/web/src/entities/generated/events.d.ts
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const dir = new URL('./events/', import.meta.url);
const out = new URL('../../apps/web/src/entities/generated/events.d.ts', import.meta.url);
const header = '/* GENERATED by packages/contracts (npm run gen:types). Do not edit by hand. */\n';

let body = '';
const names = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.schema.json')).sort()) {
  const schema = JSON.parse(readFileSync(new URL(file, dir), 'utf8'));
  names.push(schema.title);
  body += await compile(schema, schema.title, { bannerComment: '', additionalProperties: false });
}
body += `\nexport type CallEvent = ${names.join(' | ')};\n`;
mkdirSync(new URL('./', out), { recursive: true });
writeFileSync(out, header + body);

// api.d.ts 머리말
const apiOut = new URL('../../apps/web/src/entities/generated/api.d.ts', import.meta.url);
const apiBody = readFileSync(apiOut, 'utf8');
if (!apiBody.startsWith('/* GENERATED')) writeFileSync(apiOut, header + apiBody);
